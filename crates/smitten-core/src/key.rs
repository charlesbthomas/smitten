impl std::fmt::Display for Key {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.name())
    }
}

impl std::str::FromStr for Key {
    type Err = crate::ParseNameError;

    /// Reads LÖVE's name for a key, as [`Key::name`] gives it.
    fn from_str(name: &str) -> Result<Key, Self::Err> {
        Key::ALL
            .into_iter()
            .find(|key| key.name() == name)
            .ok_or_else(|| crate::ParseNameError::new("key", name))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_key_name_reads_back() {
        for key in Key::ALL {
            assert_eq!(key.name().parse::<Key>(), Ok(key));
        }
        assert_eq!(Key::LeftShift.to_string(), "lshift");
        assert!("shift".parse::<Key>().is_err());
    }
}
